// উপাধির ঝুড়ি (ক্রম ঠিক থাকে): নিজের ধরন + (ছাত্রছাত্রীর) কমন + ক্লাবের উপাধি।
window.titlePool = function (kind, club) {
  var T = window.MC_TITLES, own = T[kind] || T.male, cm = (kind === "male" || kind === "female") ? (T.commonStudent || []) : [], cl = (club && T.clubs && T.clubs[club]) || [], seen = {}, pool = [];
  own.concat(cm, cl).forEach(function (t) { if (!seen[t]) { seen[t] = 1; pool.push(t); } });
  return pool;
};
// অফলাইন/লোকাল: এই ফোনে আগে পাওয়া উপাধি বাদ। সব শেষ হলে নতুন করে শুরু (শুধু শেষটা বাদ)।
window.pickTitle = function (kind, hist, club) {
  var pool = window.titlePool(kind, club);
  var ok = pool.filter(function (t) { return hist.indexOf(t) < 0; });
  if (!ok.length) { var last = hist[hist.length - 1]; ok = pool.filter(function (t) { return t !== last; }); if (!ok.length) ok = pool; hist.length = 0; }
  return { title: ok[Math.floor(Math.random() * ok.length)], tag: "own" };
};
// অনলাইন: Supabase কাউন্টার (supabase-titles.sql) প্রতিজনকে পরের নম্বর দেয় → সবাই আলাদা উপাধি পায়।
// config.js খালি থাকলে বা নেট/সার্ভার সাড়া না দিলে ৩ সেকেন্ড পর আগের লোকাল নিয়মে চলে (খেলা আটকায় না)।
window.pickTitleOnline = async function (kind, hist, club) {
  var c = window.MC_CFG || {};
  if (!c.url || !c.key || !window.fetch) return window.pickTitle(kind, hist, club);
  try {
    var pool = window.titlePool(kind, club), ctl = new AbortController(), tm = setTimeout(function () { ctl.abort(); }, 3000);
    var r = await fetch(c.url.replace(/\/$/, "") + "/rest/v1/rpc/next_title", { method: "POST", signal: ctl.signal, headers: { "Content-Type": "application/json", apikey: c.key, Authorization: "Bearer " + c.key }, body: JSON.stringify({ p_key: kind + "|" + (club || "") }) });
    clearTimeout(tm);
    var n = Number(await r.json());
    if (!r.ok || !isFinite(n) || n < 1) throw 0;
    return { title: pool[(n - 1) % pool.length], tag: "online" };
  } catch (e) { return window.pickTitle(kind, hist, club); }
};
